// Helper: Translate a dynamic city string
export function translateCity(cityName, lang = 'en') {
  if (!cityName || lang === 'en') return cityName;
  return CITY_TRANSLATIONS[cityName]?.[lang] || cityName;
}

// Helper: Translate a dynamic category string
export function translateCategory(catName, lang = 'en') {
  if (!catName || lang === 'en') return catName;
  return CATEGORY_TRANSLATIONS[catName]?.[lang] || catName;
}

// Helper: Translate a dynamic venue string
export function translateVenue(venueName, lang = 'en') {
  if (!venueName || lang === 'en') return venueName;
  return VENUE_TRANSLATIONS[venueName]?.[lang] || venueName;
}

// Helper: Translate an entire event object safely
export function translateEvent(event, lang = 'en') {
  if (!event || lang === 'en') return event;

  const titleEntry = EVENT_DATA_TRANSLATIONS[event.title];
  const translatedTitle = titleEntry?.title?.[lang] || event.title;
  const translatedDesc = titleEntry?.description?.[lang] || event.description || event.short_description;

  const rawCatName = event.category_details?.name || event.category?.name || event.category;
  const translatedCatName = typeof rawCatName === 'string' ? translateCategory(rawCatName, lang) : rawCatName;

  const translatedCity = translateCity(event.city, lang);
  const translatedVenue = translateVenue(event.venue_name, lang);

  return {
    ...event,
    title: translatedTitle,
    description: translatedDesc || event.description,
    short_description: titleEntry?.description?.[lang] || event.short_description,
    city: translatedCity,
    venue_name: translatedVenue,
    category_details: event.category_details ? {
      ...event.category_details,
      name: translatedCatName,
    } : event.category_details,
  };
}
